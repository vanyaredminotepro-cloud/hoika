def building_lines() -> str:
    lines = []
    for key, cost in _cards.BUILDING_COSTS.items():
        name = BUILDING_NAMES.get(key, key)
        hours = _cards.BUILDING_TIMES.get(key)
        time_txt = f"{hours} ч" if hours else "?"
        lines.append(f"• {name} — {cost:,} виртуальных рублей, {time_txt}".replace(",", " "))
    return "\n".join(lines)


def army_upkeep_lines() -> str:
    lines = []
    for key, upkeep in _eco.ARMY_UPKEEP.items():
        name = ARMY_UNIT_NAMES.get(key, key)
        lines.append(f"• {name} — {upkeep} виртуальных рублей в сутки на единицу")
    return "\n".join(lines)


def tax_lines() -> str:
    lines = []
    for level, rate in _eco.TAX_PER_CAPITA.items():
        penalty = _eco.STABILITY_TAX_PENALTY.get(level, 0.0)
        penalty_txt = (
            f", штраф к стабильности {penalty:g} в неделю" if penalty else ""
        )
        lines.append(
            f"• {TAX_LEVEL_NAMES.get(level, level)} — {rate:g} виртуальных рублей "
            f"с жителя в сутки{penalty_txt}"
        )
    return "\n".join(lines)


