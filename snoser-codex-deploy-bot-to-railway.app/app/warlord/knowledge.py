def _topic_context(question: str) -> list[str]:
    q = question.lower()
    parts: list[str] = []
    seen: set[str] = set()
    for keywords, builder in _TOPICS:
        if any(word in q for word in keywords):
            text = builder()
            if text not in seen:
                seen.add(text)
                parts.append(text)
    return parts


def build_context(
    question: str,
    *,
    country: dict[str, Any] | None = None,
    countries: list[dict[str, Any]] | None = None,
    factions: list[dict[str, Any]] | None = None,
    max_names: int = 40,
) -> str:
    """Собрать контекст для ответа ассистента.

    Всегда содержит общую справку, чтобы бот никогда не отвечал
    «в базе нет информации».
    """
    parts: list[str] = [static_facts()]
    parts.extend(_topic_context(question))

    if country:
        from .cards import build_country_card

        parts.append("ДАННЫЕ О СТРАНЕ ИЗ БАЗЫ\n" + build_country_card(country))
    if countries:
        names = [str(c.get("name", "")) for c in countries[:max_names] if c.get("name")]
        if names:
            parts.append("ЗАРЕГИСТРИРОВАННЫЕ СТРАНЫ\n" + ", ".join(names))
    if factions:
        names = [str(f.get("full_name") or f.get("name") or "") for f in factions[:max_names]]
        names = [n for n in names if n]
        if names:
            parts.append("ЗАРЕГИСТРИРОВАННЫЕ ГРУППИРОВКИ\n" + ", ".join(names))

    return "\n\n".join(parts)
